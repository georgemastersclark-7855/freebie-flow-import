import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ entryPoints:['src/mentorship/schedulePattern.ts'],bundle:true,platform:'node',format:'esm',write:false });
const p = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const zone='Europe/London';
const seed={pattern:null,weeks:Array.from({length:6},(_,i)=>({id:`w${i+1}`,number:i+1,opensAt:i===0?'2026-10-18T08:43:00Z':null,deadlineAt:i===0?'2026-10-22T08:43:00Z':null})),calls:[{id:'c1',title:'Commercial Song Structure',startsAt:'2026-10-18T18:00:00Z',endsAt:'2026-10-18T19:30:00Z',weekId:'w1',joinUrl:'https://example.com/call'}]};
const input={opensAt:seed.weeks[0].opensAt,deadlineAt:seed.weeks[0].deadlineAt,callStartsAt:seed.calls[0].startsAt,callEndsAt:seed.calls[0].endsAt,callTitle:'Group coaching call',joinUrl:'https://example.com/call'};
const id=n=>`c${n}`;
const plan=p.buildWeeklyPattern(seed,input,zone,id);
assert.equal(plan.calls.length,6);
assert.equal(plan.calls[0].id,'c1');
assert.equal(plan.calls[0].title,'Commercial Song Structure');
assert.equal(plan.calls[1].startsAt,'2026-10-25T19:00:00.000Z');
assert.equal(plan.weeks[1].opensAt,'2026-10-25T09:43:00.000Z');
assert.equal(plan.weeks[5].deadlineAt,'2026-11-26T09:43:00.000Z');
assert.equal(p.buildWeeklyPattern(plan,input,zone,()=>{throw Error('must reuse calls');}).calls.length,6);
let exception=p.editWeekDates(plan,'w3',{opensAt:plan.weeks[2].opensAt,deadlineAt:'2026-11-06T12:00:00Z'},'one',zone,id);
exception=p.editCallDates(exception,{...exception.calls[3],startsAt:'2026-11-10T19:00:00Z',endsAt:'2026-11-10T20:30:00Z'},'one',zone,id);
const shifted=p.editWeekDates(exception,'w1',{opensAt:'2026-10-19T08:43:00Z',deadlineAt:exception.weeks[0].deadlineAt},'series',zone,id);
assert.equal(shifted.weeks[0].deadlineAt,'2026-10-23T08:43:00.000Z');
assert.equal(shifted.weeks[1].opensAt,'2026-10-26T09:43:00.000Z');
assert.equal(shifted.weeks[2].deadlineAt,'2026-11-06T12:00:00Z');
assert.equal(shifted.calls.find(c=>c.id==='c4').startsAt,'2026-11-10T19:00:00Z');
assert.equal(shifted.calls[0].startsAt,'2026-10-19T18:00:00.000Z');
const callShift=p.editCallDates(shifted,{...shifted.calls[0],startsAt:'2026-10-20T17:00:00Z',endsAt:'2026-10-20T18:30:00Z'},'series',zone,id);
assert.equal(callShift.calls.find(c=>c.id==='c2').startsAt,'2026-10-27T18:00:00.000Z');
assert.deepEqual(callShift.weeks,shifted.weeks);
assert.equal(callShift.calls.find(c=>c.id==='c4').startsAt,'2026-11-10T19:00:00Z');
const reset=p.restorePatternDate(callShift,'call','c4',zone);
assert.equal(reset.calls.find(c=>c.id==='c4').startsAt,'2026-11-10T18:00:00.000Z');
assert.ok(!reset.pattern.callExceptions.includes('c4'));
const topic=p.editCallDates(plan,{...plan.calls[1],title:'Vocal Production'},'one',zone,id);
assert.equal(topic.pattern.callExceptions.length,0);
assert.equal(topic.calls.find(c=>c.id==='c1').title,'Commercial Song Structure');
const firstOneoff=p.editWeekDates(plan,'w1',{opensAt:'2026-10-19T08:43:00Z',deadlineAt:plan.weeks[0].deadlineAt},'one',zone,id);
assert.equal(firstOneoff.weeks[1].opensAt,plan.weeks[1].opensAt);
assert.ok(firstOneoff.pattern.weekExceptions.w1.opensAt);
const legacy=structuredClone(seed); legacy.weeks[2].deadlineAt='2026-11-06T12:00:00Z';
assert.equal(p.buildWeeklyPattern(legacy,input,zone,id).weeks[2].deadlineAt,legacy.weeks[2].deadlineAt);
const external=structuredClone(plan); external.calls[1].startsAt='2026-10-26T19:00:00Z'; external.calls[1].endsAt='2026-10-26T20:30:00Z';
assert.equal(p.buildWeeklyPattern(external,input,zone,id).calls[1].startsAt,external.calls[1].startsAt);
assert.throws(()=>p.editWeekDates(plan,'w2',{opensAt:plan.weeks[1].opensAt,deadlineAt:'2026-10-01T00:00:00Z'},'one',zone,id),/deadline must/);
assert.throws(()=>p.buildWeeklyPattern(seed,{...input,callEndsAt:null},zone,id),/both/);
assert.throws(()=>p.buildWeeklyPattern(seed,{...input,joinUrl:'javascript:bad'},zone,id),/HTTPS/);
assert.throws(()=>p.shiftInstant('2026-10-18T00:30:00Z',10080,zone),/occurs twice/);
assert.equal(p.shiftLocal('2026-12-31T19:00',1440),'2027-01-01T19:00');
assert.equal(p.shiftInstant('2026-03-22T19:00:00Z',10080,zone),'2026-03-29T18:00:00.000Z');
assert.equal(seed.calls.length,1);
console.log('Passed: six-week generation, DST in both directions, stable call IDs, independent topics, one-off dates, exception resets, whole-programme/call-only shifts, legacy edits, invalid dates and links.');
const unlinked=structuredClone(seed); unlinked.calls[0].weekId=null;
const adopted=p.buildWeeklyPattern(unlinked,input,zone,id);
assert.equal(adopted.calls.length,6); assert.equal(adopted.calls[0].id,'c1'); assert.equal(adopted.calls[0].weekId,'w1');
assert.throws(()=>p.buildWeeklyPattern(plan,{...input,callStartsAt:null,callEndsAt:null},zone,id),/Keep the weekly/);
console.log('Passed: existing unlinked first call adopted without duplication; linked call pattern cannot be accidentally cleared.');
