import assert from 'node:assert/strict';
import { build } from 'esbuild';
const built = await build({ entryPoints: ['src/mentorship/schedule.ts'], bundle: true, platform: 'node', format: 'esm', write: false });
const s = await import(`data:text/javascript;base64,${Buffer.from(built.outputFiles[0].text).toString('base64')}`);
const now = Date.parse('2026-10-07T12:00:00Z');
const week = { number: 1, phase: 'current', opensAt: '2026-10-05T12:00:00Z', deadlineAt: '2026-10-09T12:00:00Z' };
const empty = { state: 'not_started', ideas: [] };
assert.equal(s.weekTiming(week, empty, now).elapsed, 50);
assert.equal(s.weekTiming(week, empty, now).state, 'open');
assert.equal(s.weekTiming(week, empty, now + 86400000).state, 'soon');
assert.equal(s.weekTiming(week, empty, Date.parse(week.deadlineAt)).state, 'overdue');
assert.equal(s.weekTiming(week, { ...empty, state: 'late' }, now + 9e8).state, 'submitted');
assert.equal(s.weekTiming(week, { ...empty, state: 'submitted', feedback: {} }, now).state, 'feedback');
assert.equal(s.weekTiming(week, { ...empty, state: 'submitted', feedback: { actionConfirmedAt: 'yes' } }, now).state, 'submitted');
assert.equal(s.weekTiming({ ...week, deadlineAt: undefined }, empty, now).state, 'unscheduled');
assert.equal(s.weekTiming({ ...week, deadlineAt: 'invalid' }, empty, now).elapsed, undefined);
assert.equal(s.weekTiming({ ...week, opensAt: '2026-10-08T12:00:00Z' }, empty, now).state, 'upcoming');
assert.equal(s.weekTiming({ ...week, opensAt: undefined }, empty, now).elapsed, undefined);
assert.equal(s.countdown(now + 61000, now), '2 min');
assert.equal(s.countdown(now + 3600000, now), '1h 0m');
const calls = [{ id: 'past', startsAt: '2026-10-06T10:00:00Z' }, { id: 'now', startsAt: '2026-10-07T11:30:00Z' }, { id: 'next', startsAt: '2026-10-07T15:00:00Z' }];
assert.equal(s.nextScheduledCall(calls, now).id, 'now');
assert.equal(s.nextScheduledCall(calls, Date.parse('2026-10-07T13:00:00Z')).id, 'next');
assert.equal(s.nextScheduledCall(calls, now + 86400000), undefined);
const event = s.callCalendarEvent({ ...calls[1], title: 'Call, one; with Rob\nA new line', circleUrl: 'https://example.com/meet?a=1&b=2' });
assert.equal(event.endsAt, '2026-10-07T13:00:00.000Z');
const google = new URL(s.googleCalendarUrl(event));
assert.equal(google.searchParams.get('dates'), '20261007T113000Z/20261007T130000Z');
assert.equal(google.searchParams.get('text'), event.title);
const ics = s.calendarFile(event, now);
assert.ok(ics.includes('SUMMARY:Call\\, one\\; with Rob\\nA new line'));
assert.ok(ics.includes('DTSTART:20261007T113000Z\r\n'));
assert.equal(s.calendarFile(event, now), s.calendarFile(event, now));
const long = s.calendarFile({ ...event, title: '😀 music é'.repeat(60) }, now);
assert.ok(long.split('\r\n').every(line => Buffer.byteLength(line, 'utf8') <= 75));
assert.ok(long.replace(/\r\n /g, '').includes('SUMMARY:' + '😀 music é'.repeat(60)));
assert.equal(s.callCalendarEvent({ startsAt: 'bad' }), undefined);
assert.equal(s.safeScheduleUrl('javascript:alert(1)'), undefined);
assert.equal(s.deadlineCalendarEvent({ number: 1 }, 'cohort'), undefined);
assert.ok(!s.calendarFile(s.deadlineCalendarEvent(week, 'cohort'), now).includes('DTEND'));
assert.ok(s.googleCalendarUrl(s.callCalendarEvent({ id: 'dst', title: 'Call', startsAt: '2026-10-25T19:00:00+00:00', endsAt: '2026-10-25T20:30:00+00:00' })).includes('20261025T190000Z'));
console.log('Passed: deadline boundaries, submitted/feedback states, live-call rollover, calendar dates, DST instant, escaping, UTF-8 folding and missing-date handling.');
const adminBuild = await build({ entryPoints: ['src/mentorship/scheduleAdminApi.ts'], bundle: true, platform: 'node', format: 'esm', write: false, plugins: [{name:'stub-client',setup(build){build.onResolve({filter:/^@\/integrations\/supabase\/client$/},()=>({path:'supabase-client',namespace:'stub'}));build.onLoad({filter:/.*/,namespace:'stub'},()=>({contents:'export const supabase = {};',loader:'js'}));}}] });
const zone = await import(`data:text/javascript;base64,${Buffer.from(adminBuild.outputFiles[0].text).toString('base64')}`);
assert.equal(zone.scheduleLocalInputToIso('2026-10-18T19:00','Europe/London'), '2026-10-18T18:00:00.000Z');
assert.equal(zone.scheduleLocalInputToIso('2026-10-25T19:00','Europe/London'), '2026-10-25T19:00:00.000Z');
assert.equal(zone.scheduleIsoToLocalInput('2026-10-18T18:00:00Z','Europe/London'), '2026-10-18T19:00');
assert.throws(()=>zone.scheduleLocalInputToIso('2026-03-29T01:30','Europe/London'), /does not exist/);
assert.throws(()=>zone.scheduleLocalInputToIso('2026-10-25T01:30','Europe/London'), /occurs twice/);
assert.throws(()=>zone.scheduleLocalInputToIso('2026-02-30T12:00','Europe/London'), /valid calendar/);
assert.equal(zone.scheduleLocalInputToIso('2026-10-18T19:00','Asia/Kolkata'), '2026-10-18T13:30:00.000Z');
assert.equal(zone.scheduleLocalInputToIso('','Europe/London'), null);
console.log('Passed: cohort timezone conversion, BST/GMT transition, nonexistent/repeated DST hours, invalid date rejection and half-hour offsets.');
const gridBuild = await build({ entryPoints: ['src/mentorship/staffCalendar.ts'], bundle: true, platform: 'node', format: 'esm', write: false, plugins: [{name:'stub-client',setup(build){build.onResolve({filter:/^@\/integrations\/supabase\/client$/},()=>({path:'supabase-client',namespace:'stub'}));build.onLoad({filter:/.*/,namespace:'stub'},()=>({contents:'export const supabase = {};',loader:'js'}));}}] });
const grid = await import(`data:text/javascript;base64,${Buffer.from(gridBuild.outputFiles[0].text).toString('base64')}`);
assert.equal(grid.shiftCalendarMonth('2026-12',1),'2027-01');
assert.equal(grid.shiftCalendarMonth('2026-01',-1),'2025-12');
assert.equal(grid.calendarMonthDays('2026-10')[0],'2026-09-28');
assert.equal(grid.calendarMonthDays('2026-10').at(-1),'2026-11-01');
assert.equal(grid.calendarMonthDays('2028-02').filter(day=>day.startsWith('2028-02')).length,29);
assert.equal(grid.calendarMonthDays('2026-03').length,42);
const mapped = grid.calendarEvents([{id:'w1',number:1,opensAt:null,deadlineAt:'2026-10-18T23:30:00Z'}],[{id:'c1',title:'DST call',startsAt:'2026-10-25T19:00:00Z'}],'Europe/London');
