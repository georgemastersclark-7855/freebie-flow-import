import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const js = ts.transpileModule(readFileSync('src/mentorship/onboardingPlan.ts','utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { emptyOnboardingPlan, readOnboardingPlan, validateOnboardingPlan, onboardingNoteBody } = await import(`data:text/javascript;base64,${Buffer.from(js).toString('base64')}`);
const plan = emptyOnboardingPlan();
validateOnboardingPlan(plan);
assert.match(onboardingNoteBody(plan), /Draft/);
plan.status = 'agreed';
assert.throws(() => validateOnboardingPlan(plan), /Record the goal/);
plan.musicReviewed = true;
Object.assign(plan.answers, { goal:'Release my song',music:'Song v3, 0:30 to 1:20',focus:'Leave space for the hook',practice:'Try a shorter verse in the developed song',listenFor:'Whether the hook lands clearly' });
validateOnboardingPlan(plan);
plan.extraReview = 'requested';
assert.match(onboardingNoteBody(plan), /Rob has not agreed yet/);
plan.extraReview = 'agreed';
assert.throws(() => validateOnboardingPlan(plan), /agreed date/);
Object.assign(plan.answers, {extraTrack:'Existing release v2; review full arrangement',extraDate:'2026-10-21'});
validateOnboardingPlan(plan);
plan.answers.handover = 'Keep the quote “get to the hook”\n\nGoal headings in free text remain intact.';
assert.deepEqual(readOnboardingPlan(JSON.parse(JSON.stringify(plan))), plan);
assert.match(onboardingNoteBody(plan), /Additional review agreed by Rob/);
assert.equal(readOnboardingPlan({ ...plan, answers:{...plan.answers, goal:5} }), null);
assert.equal(readOnboardingPlan({ ...plan, template:'future-version' }), null);
assert.equal(readOnboardingPlan({ ...plan, extraReview:'toString' }), null);
assert.equal(readOnboardingPlan(null), null);
console.log('Onboarding: draft/agreed validation, extra review agreement, text preservation and unknown data rejection passed.');
